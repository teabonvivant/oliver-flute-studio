def prompt_for(module, post: dict, scene: str, index: int) -> tuple[str, str, str]:
    base_title, _ = module.split_title(post)
    filename = f"assets/images/article-covers/{Path(post['url']).stem}-cover.jpg"
    alt = f"{post['category']}文章封面：{base_title}，實物場景呈現{post['focus']}"

    opener = OPENERS[(post["number"] + index) % len(OPENERS)]
    camera = CAMERA_DIRECTIONS[(index + post["number"] * 2) % len(CAMERA_DIRECTIONS)]
    purpose = PURPOSE_LINES[(index + post["number"]) % len(PURPOSE_LINES)].format(
        focus=post["focus"],
        method=post["method"],
    )
    material = MATERIAL_DIRECTIONS[post["category"]]
    prompt = "\n".join([
        f"{opener}〈{post['title']}〉。",
        scene,
        camera,
        purpose,
        material,
    ])
    return filename, alt, prompt


def main() -> None:
    module = load_site_module()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    groups = grouped_posts(module)

    missing = [category for category in groups if category not in SCENES]
    if missing:
        raise RuntimeError(f"Missing scene groups: {missing}")

    rows = [
        "# 100 篇文章圖片生成提示詞",
        "",
        "用途：每篇文章各自一張實物相片式封面。這版已避免把同一套模板重複 100 次；每段 prompt 都有獨立場景、物件關係和拍攝重點。",
        "",
        "共同規格：橫向 16:9，建議 1200x675 或以上，JPG/WebP。整體氣質要安靜、克制、專業，像高級演奏家網站的 editorial still life photography。",
        "",
        "共同禁止：全部圖片不用加入老師樣貌、學生、真人角色、可辨認人臉、可讀文字、logo、水印、證書、虛假課堂、卡通插畫、3D 渲染感或網紅打卡風；不要直接複製網上圖片構圖。",
        "",
    ]

    seen_prompts: set[str] = set()
    global_index = 1
    for category, posts in groups.items():
        scenes = SCENES[category]
        if len(posts) != 20 or len(scenes) != 20:
            raise RuntimeError(f"{category}: posts={len(posts)}, scenes={len(scenes)}")
        for local_index, post in enumerate(posts):
            filename, alt, prompt = prompt_for(module, post, scenes[local_index], global_index)
            if prompt in seen_prompts:
                raise RuntimeError(f"Duplicate prompt: {post['url']}")
            seen_prompts.add(prompt)
            rows.extend(
                [
                    f"## {global_index:03d}. {post['title']}",
                    "",
                    f"- 文章：`{post['url']}`",
                    f"- 分類：{post['category']}",
                    f"- 建議檔名：`{filename}`",
                    f"- Alt text：{alt}",
                    "",
                    "```text",
                    prompt,
                    "```",
                    "",
                ]
            )
            global_index += 1

    if len(seen_prompts) != 100:
        raise RuntimeError(f"Expected 100 prompts, got {len(seen_prompts)}")

    OUTPUT.write_text("\n".join(rows), encoding="utf-8", newline="\n")
    print(f"written={OUTPUT}")
    print(f"prompts={len(seen_prompts)}")


if __name__ == "__main__":
    main()
